export function calculateGrade(score: number): { grade: 'A' | 'B' | 'C' | 'D'; label: string; color: string; desc: string } {
  if (score >= 90) {
    return { grade: 'A', label: 'เกรด A - ดีเยี่ยม (Excellent)', color: 'text-emerald-700 bg-emerald-50 border-emerald-200', desc: 'ปฏิบัติตาม Sales SOP ครบถ้วน ไร้ข้อบกพร่อง' };
  } else if (score >= 80) {
    return { grade: 'B', label: 'เกรด B - ดี (Good)', color: 'text-blue-700 bg-blue-50 border-blue-200', desc: 'ปฏิบัติตามขั้นตอนได้ดี มีจุดเล็กน้อยที่เสริมต่อได้' };
  } else if (score >= 70) {
    return { grade: 'C', label: 'เกรด C - พอใช้ (Fair)', color: 'text-amber-700 bg-amber-50 border-amber-200', desc: 'ผ่านเกณฑ์ขั้นต่ำ มีจุดหลุดในขั้นตอนสำคัญ ควรปรับปรุง' };
  } else {
    return { grade: 'D', label: 'เกรด D - ต้องปรับปรุง (Needs Training)', color: 'text-rose-700 bg-rose-50 border-rose-200', desc: 'ไม่ผ่านเกณฑ์มาตรฐาน ต้องได้รับการโค้ชชิ่งและประเมินซ้ำ' };
  }
}
